/**
 * Writes docs/QLOO_WALKTHROUGH.md: a redacted request → result trace for one seeded show, built
 * from its stored Qloo call ledger. Usage: tsx scripts/walkthrough.ts [mode=mock|live] [seed=sports]
 * Only IDs, tool names, statuses and result counts appear; no credential is ever in the ledger.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { LedgerCall, RunState, Show } from "@housemix/shared";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mode = process.argv[2] ?? "mock";
const key = process.argv[3] ?? "sports";
const file = path.join(ROOT, "fixtures/seed", mode, `${key}.json`);
if (!fs.existsSync(file)) {
  console.error(`No seed at ${file}.`);
  process.exit(1);
}
const { show, ledger, run } = JSON.parse(fs.readFileSync(file, "utf8")) as { show: Show; ledger: LedgerCall[]; run: RunState };
const short = (v: unknown): string => {
  if (Array.isArray(v)) return `[${v.map(short).join(", ")}]`;
  if (typeof v === "string") return /^[0-9a-f]{8}-[0-9a-f]{4}-/.test(v) ? `${v.slice(0, 8)}…` : v.startsWith("urn:tag:") ? v : JSON.stringify(v);
  return JSON.stringify(v);
};
const args = (a: Record<string, unknown>) =>
  Object.entries(a)
    .map(([k, v]) => `${k}=${short(v)}`)
    .join(", ");
const nameOf = (id: string) => show.entities.find((e) => e.qlooId === id)?.name ?? ledger.flatMap((c) => c.results).find((r) => r.entity_id === id || r.id === id)?.name ?? id.slice(0, 8);

const resolve = ledger.filter((c) => c.runId === `resolve_${show.id}`).sort((a, b) => a.at.localeCompare(b.at));
const plan = ledger.filter((c) => c.runId === run.runId).sort((a, b) => a.at.localeCompare(b.at));
const crit = run.events.filter((e) => e.type === "critic");
const out: string[] = [];
out.push(`# Qloo walkthrough: ${show.title}`, "");
out.push(
  mode === "mock"
    ? "> **MOCK DATA.** This walkthrough was generated from the mock Qloo server (fictional fixtures, same tool names, inputs and envelope as `qloo mcp` 0.1.26). Re-run `npx tsx scripts/walkthrough.ts live sports` after `npm run qloo:verify` and the live re-seed to replace it with live results."
    : "> Generated from live `qloo mcp` results.",
  "",
);
out.push(`Show: ${show.input.mode}, ${show.input.venue}, ${show.input.city}, ${show.input.date}. Generated by \`scripts/walkthrough.ts\` from the stored call ledger. IDs are truncated; no key or personal data is ever sent or stored.`, "");
out.push("## 1. Intake: every name becomes a confirmed Qloo ID", "", "| # | Tool | Inputs | Status | What happened |", "| --- | --- | --- | --- | --- |");
resolve.forEach((c, i) => {
  const ent = show.entities.find((e) => e.callId === c.callId);
  const what = c.status === "needs_input" ? `ambiguous: ${c.issues[0]?.candidates.length ?? 0} candidates shown as a confirm card` : c.resultIds[0] ? `resolved to ${nameOf(c.resultIds[0])}${ent?.summary === "Confirmed by the operator." ? " (operator's choice)" : ""}` : c.status;
  out.push(`| ${i + 1} | \`${c.tool}\` | ${args(c.args)} | ${c.status} | ${what} |`);
});
out.push("", "Any `needs_input` stops the flow: the operator picks a candidate, and the choice is re-checked with `qloo_describe` by ID. Nothing is auto-picked.", "");
out.push("## 2. Plan run: the agents' Qloo calls", "", `${plan.length} calls by the CrowdReader, Programmers, SponsorFit and Wildcard subagents (cache hits included).`, "", "| # | Agent | Tool | Inputs (IDs only) | Status | Results | Attempts |", "| --- | --- | --- | --- | --- | --- | --- |");
plan.forEach((c, i) => out.push(`| ${i + 1} | ${c.agent} | \`${c.tool}\` | ${args(c.args)} | ${c.status} | ${c.resultIds.length} | ${c.cached ? "cache" : c.attempts} |`));
out.push("", "Retries happen only when the envelope says `error.retryable: true` (attempts > 1 above).", "");
out.push("## 3. From results to plan items", "");
for (const s of show.plan?.slots ?? []) {
  out.push(`### ${s.label} (${s.timeRange})`, "");
  for (const it of s.items.slice(0, 3)) {
    out.push(`- **${it.pick.name}**${it.isWildcard ? " (stretch)" : ""}`);
    out.push(`  - Qloo says: ${it.qlooSays}`);
    out.push(`  - Our interpretation: ${it.interpretation}`);
    out.push(`  - Evidence: ${it.evidence.map((e) => `\`${e.tool}\` ${e.status} (call ${e.callId})`).join(", ")}`);
  }
  if (s.items.length > 3) out.push(`- …and ${s.items.length - 3} more.`);
  out.push("");
}
out.push("## 4. What the Critic removed", "");
out.push(crit.length ? crit.map((c) => (c.type === "critic" ? `- ${c.slotKey}: ${c.pick}: ${c.reason}` : "")).join("\n") : "- Nothing was removed on this run.");
out.push("", "## 5. Limitations attached to this plan", "", ...(show.plan?.limitations ?? []).map((l) => `- ${l}`), "");
fs.writeFileSync(path.join(ROOT, "docs/QLOO_WALKTHROUGH.md"), `${out.join("\n")}\n`);
console.log("wrote docs/QLOO_WALKTHROUGH.md");
