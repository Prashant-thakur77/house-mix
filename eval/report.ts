/** Regenerates eval/REPORT.md from eval/results/*.json. Missing results are shown as pending, never estimated. */
import fs from "node:fs";
import path from "node:path";
import { EVAL_ROOT, RESULTS, median, readJson } from "./lib.ts";

type W = { p: number; lo: number; hi: number };
const r = <T>(name: string) => readJson<T | null>(path.join(RESULTS, `${name}.json`), null);
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const ci = (w: W) => `${pct(w.p)} (95% CI ${pct(w.lo)}–${pct(w.hi)})`;
const live = (x: { qlooMode?: string } | null) => x && x.qlooMode === "live";

const ab = r<{
  qlooMode: string;
  raters: number;
  ratings: number;
  overall: { wins: number; losses: number; ties: number; winRate: W };
  perSlot: Record<string, { wins: number; losses: number; ties: number; winRate: W }>;
  fit: { houseMix: number; l0: number };
  fleissKappa: number | null;
}>("ab");
const bt = r<{
  qlooMode: string;
  chosenOnDev: unknown;
  test: Record<"houseMix" | "p0" | "l0", { n: number; hitAt10: number; mrr: number }>;
  rows: { genre: string; truthResolved: number; houseMix: { hit: boolean }; p0: { hit: boolean } }[];
}>("backtest");
const ev = r<{
  qlooMode: string;
  houseMix: { items: number; valid: number; rate: number; criticDrops: number };
  l0: { items: number; unresolvedByQloo: number; unresolvedPerPlan: number; ambiguousInQloo?: number };
}>("evidence");
const judge = r<{
  qlooMode: string;
  model: string;
  pairs: number;
  overall: { wins: number; losses: number; ties: number; winRate: W };
  perSlot: Record<string, { wins: number; losses: number; ties: number; winRate: W }>;
  fit: { houseMix: number; l0: number };
  positionConsistency: number;
}>("ab_judge");
const judgeV1 = r<{ qlooMode: string; model: string; pairs: number; overall: { wins: number; losses: number; ties: number }; fit: { houseMix: number; l0: number } }>("ab_judge_v1");
type Real = { picks: number; tooBig: number; examples: string[]; unresolved?: number };
type Rep = { picks: number; repeated: number; top: string[] };
const value = r<{
  qlooMode: string;
  realism: Record<"houseMixV1" | "houseMixV2" | "l0", Real>;
  specificity: Record<"houseMix" | "l0" | "houseMixBrands" | "l0Brands", Rep>;
  sensitivity: { crowds: number; pairs: number; meanOverlap: number; maxOverlap: number };
  location?: { shows: number; meanAwayOverlap: number; meanNoCityOverlap: number; changed: number };
  repeatability?: { calls: number; sameSet: number; sameOrder: number };
  explainability?: { picks: number; explained: number; recommended: number; cited: number };
  music?: { artists: number; withSongs: number; filledByQloo: number; explicitLeftOut: number; playlists: number; minutesPlanned: number };
  latency?: Record<string, { calls: number; medianMs: number; maxMs: number }>;
}>("qloo_value");
const plans = r<{ qlooMode: string; plans: { id: string; durationMs: number; stats: { qlooCalls: number; cacheHits: number; costUsd: number } }[] }>("plans");

const out: string[] = [
  "# House Mix evaluation report",
  "",
  "Generated by `npm run eval:report` from `eval/results/*.json`. Every number below comes from those files; nothing is estimated or taken from mock data.",
  "",
];
out.push("## Results", "", "| Claim | House Mix | Baseline | Notes |", "| --- | --- | --- | --- |");
if (live(ab) && ab)
  out.push(
    `| Blind A/B win rate vs LLM-only (L0) | ${ci(ab.overall.winRate)} | L0 | ${ab.overall.wins}–${ab.overall.losses} (ties ${ab.overall.ties}), ${ab.raters} raters, κ = ${ab.fleissKappa?.toFixed(2) ?? "n/a"} |`,
  );
else out.push("| Blind A/B win rate vs LLM-only (L0), human raters | pending | L0 | live pairs are generated; needs human raters at /rate |");
if (live(judgeV1) && judgeV1)
  out.push(
    `| Blind A/B, automated judge, first run (before the fixes below; House Mix workers on Haiku, L0 on Sonnet) | ${judgeV1.overall.wins}–${judgeV1.overall.losses} (ties ${judgeV1.overall.ties}) of ${judgeV1.pairs} test pairs | L0 | mean fit ${judgeV1.fit.houseMix.toFixed(2)} vs ${judgeV1.fit.l0.toFixed(2)} of 5 |`,
  );
if (live(judge) && judge)
  out.push(
    `| Blind A/B, automated judge (${judge.model}, both orders) | ${judge.overall.wins}–${judge.overall.losses} (ties ${judge.overall.ties}) of ${judge.pairs} test pairs | L0 | win rate ${ci(judge.overall.winRate)}; mean fit ${judge.fit.houseMix.toFixed(2)} vs ${judge.fit.l0.toFixed(2)} of 5; same verdict in both orders ${pct(judge.positionConsistency)}. Secondary signal: a Claude judge may share the planner's tastes |`,
  );
if (live(bt) && bt) {
  out.push(`| Support act in top 10 (hit@10) | ${pct(bt.test.houseMix.hitAt10)} | P0 ${pct(bt.test.p0.hitAt10)} · L0 ${pct(bt.test.l0.hitAt10)} | n = ${bt.test.houseMix.n} test shows |`);
  out.push(`| Mean reciprocal rank | ${bt.test.houseMix.mrr.toFixed(3)} | P0 ${bt.test.p0.mrr.toFixed(3)} · L0 ${bt.test.l0.mrr.toFixed(3)} | |`);
} else out.push("| Support act in top 10 (hit@10) | pending | P0 · L0 | needs live Qloo + setlist.fm key |");
if (live(ev) && ev) {
  out.push(
    `| Items with a valid Qloo citation | ${pct(ev.houseMix.rate)} (${ev.houseMix.valid}/${ev.houseMix.items}); the Critic removed ${ev.houseMix.criticDrops} unsupported items before they reached a plan | L0 0% (no citations) | |`,
  );
  out.push(`| L0 picks live Qloo cannot find | – | ${ev.l0.unresolvedByQloo} of ${ev.l0.items} | L0 did not invent entities |`);
  if (ev.l0.ambiguousInQloo !== undefined)
    out.push(
      `| Picks that are ambiguous in Qloo (a person must choose before anything can use them) | 0 (every pick is a confirmed Qloo ID) | ${ev.l0.ambiguousInQloo} of ${ev.l0.items} (${pct(ev.l0.ambiguousInQloo / Math.max(1, ev.l0.items))}) | |`,
    );
} else out.push("| Items with a valid Qloo citation | pending | L0 | needs live plans |");
out.push("");

if (live(value) && value) {
  const R = value.realism;
  const S = value.specificity;
  const frac = (a: number, b: number) => `${a} of ${b} (${pct(a / Math.max(1, b))})`;
  out.push(
    "## What Qloo adds, measured without a judge",
    "",
    "Free checks on the same eval plans plus Qloo calls (`npm run eval:qloo`); no Claude calls.",
    "",
    "| Check | House Mix | L0 (Claude alone) | What it means |",
    "| --- | --- | --- | --- |",
    `| Opener / interval / halftime acts bigger than the headliner (Qloo popularity at or above the headliner's, or 0.99) | ${frac(R.houseMixV2.tooBig, R.houseMixV2.picks)} (first run: ${frac(R.houseMixV1.tooBig, R.houseMixV1.picks)}) | ${frac(R.l0.tooBig, R.l0.picks)}; ${R.l0.unresolved} more Qloo could not pin down | Qloo's popularity makes "smaller than the headliner" a rule the server enforces. L0's included ${R.l0.examples.slice(0, 2).join(" and ")} |`,
    `| Picks repeated from another show's plan, across ${7} different shows | ${frac(S.houseMix.repeated, S.houseMix.picks)} | ${frac(S.l0.repeated, S.l0.picks)} | Qloo's picks follow each crowd; L0 falls back on defaults (${S.l0.top.slice(0, 2).join(", ")}) |`,
    `| Sponsors repeated from another show | ${frac(S.houseMixBrands.repeated, S.houseMixBrands.picks)} | ${frac(S.l0Brands.repeated, S.l0Brands.picks)} | the same brand pitched to every crowd is not a fit score |`,
    `| Overlap between Qloo's top 10 artists for two different crowds | ${pct(value.sensitivity.meanOverlap)} on average across ${value.sensitivity.pairs} pairs of ${value.sensitivity.crowds} crowds (max ${pct(value.sensitivity.maxOverlap)}) | – | change the bill and the recommendations change completely |`,
    ...(value.location
      ? [
          `| Overlap when the same bill is asked for in a city on another continent (London ↔ Los Angeles) | ${pct(value.location.meanAwayOverlap)} on average; ${value.location.changed} of ${value.location.shows} lists changed (with no city: ${pct(value.location.meanNoCityOverlap)}) | – | where the show is changes who the crowd wants; Qloo answers for the city, not just the bill |`,
        ]
      : []),
    ...(value.repeatability
      ? [
          `| Same call asked twice, cache bypassed | ${value.repeatability.sameOrder} of ${value.repeatability.calls} identical, in the same order | – | a cited call ID can be re-run and checked by anyone |`,
        ]
      : []),
    ...(value.explainability
      ? [
          `| Plan picks that carry Qloo's own reason (which input signals drove them, and how much) | ${frac(value.explainability.explained, value.explainability.picks)}; ${value.explainability.cited === value.explainability.picks ? "every one" : frac(value.explainability.cited, value.explainability.picks)} cites a Qloo call | 0 (L0's reasons are its own prose) | the "why" on each card is Qloo's explainability, not a model's guess |`,
        ]
      : []),
    "",
    "These say Qloo grounds the picks in each crowd and makes booking rules enforceable. They do not say the picks taste better: the automated judge above still prefers L0 on taste.",
    "",
  );
  if (value.music)
    out.push(
      `**Hear the night (the five demo shows).** ${value.music.withSongs} of the ${value.music.artists} artists Qloo picked have real songs to play; ${value.music.filledByQloo} more were added by \`qloo_recommend\` when a slot ran short; ${value.music.playlists} playlists hold ${value.music.minutesPlanned} minutes of music${value.music.explicitLeftOut ? `; ${value.music.explicitLeftOut} explicit songs were left out for all-ages shows` : ""}.`,
      "",
    );
  if (value.latency)
    out.push(
      "**Qloo call times (the demo shows' ledgers, cache hits excluded).** " +
        Object.entries(value.latency)
          .map(([t, v]) => `${t.replace("qloo_", "")} median ${(v.medianMs / 1000).toFixed(1)} s (${v.calls} calls, slowest ${(v.maxMs / 1000).toFixed(1)} s)`)
          .join("; ") +
        ". Slow outliers happen; results are cached for 24 hours, so a repeat run reuses them, and a call is retried only when Qloo says the error is retryable.",
      "",
    );
}

if (live(judgeV1) && judgeV1) {
  out.push(
    "## What the first run found, and what changed",
    "",
    `The first automated-judge run went ${judgeV1.overall.wins}–${judgeV1.overall.losses} against House Mix. The judge's reasons were specific, and each became a rule the server enforces or a prompt change:`,
    "",
    "- **Openers bigger than the headliner** (Coldplay and Gorillaz to open for Linkin Park; Charli XCX for Sabrina Carpenter). Acts in opener and halftime slots must now have a Qloo popularity below the headliner's and below 0.99; the evidence gate rejects the rest.",
    "- **Food and bars across the city** (Mayfair for a Wembley crowd; Shoreditch for Stamford Bridge). Place slots now search around the venue's own address with Qloo's restaurant, bar and pub tags, and the gate rejects places that did not come from that search.",
    "- **Odd sponsors** (other sports franchises, governments, news outlets). The sponsor agent now keeps to consumer brands that could run an activation.",
    "- **Interpretations that recited scores, and clock times that overlapped.** Interpretations now explain the crowd logic with at most one number; actions give the order, not clock times.",
    "- **A model mismatch.** The first run's House Mix workers ran on Haiku while L0 ran on Sonnet. The second run uses Sonnet for both.",
    "",
  );
}

if (live(plans) && plans?.plans.length) {
  const p = plans.plans;
  const calls = p.map((x) => x.stats.qlooCalls);
  const hits = p.reduce((s, x) => s + x.stats.cacheHits, 0);
  const total = p.reduce((s, x) => s + x.stats.qlooCalls + x.stats.cacheHits, 0);
  out.push(
    "## Operations",
    "",
    `- Median plan time: ${(median(p.map((x) => x.durationMs)) / 1000).toFixed(0)} s over ${p.length} plans.`,
    `- Qloo calls per plan (median): ${median(calls)}.`,
    `- Cache hit rate: ${pct(hits / Math.max(1, total))}.`,
    `- Claude cost per plan (median): $${median(p.map((x) => x.stats.costUsd)).toFixed(3)}.`,
    "",
  );
} else out.push("## Operations", "", "Pending live plans.", "");

out.push("## Negative result", "");
const negatives: string[] = [];
if (live(judge) && judge && judge.overall.wins <= judge.overall.losses)
  negatives.push(
    `**The automated judge still prefers Claude alone overall** (${judge.overall.wins}–${judge.overall.losses}, ties ${judge.overall.ties}; mean fit ${judge.fit.houseMix.toFixed(2)} vs ${judge.fit.l0.toFixed(2)} of 5). Its reasons after the fixes: Claude alone's walk-in lists track the specific fan base (nu-metal for Linkin Park, terrace anthems for Chelsea vs United) where Qloo's ranking returns broader stadium acts; its sponsors are obvious category fits (kit makers, the clubs' beer) where Qloo ranks fashion labels; and House Mix's text still reads like ranking output ("ranks 3 of 10", "no fit score"). Openers were the one slot the fixes turned around (${judge.perSlot.openers ? `${judge.perSlot.openers.wins}–${judge.perSlot.openers.losses}` : "n/a"}).`,
  );
if (live(ev) && ev && ev.l0.unresolvedByQloo === 0)
  negatives.push(`We expected Claude alone to invent entities. It did not: live Qloo found all ${ev.l0.items} of its picks. Its weakness is ambiguity, not invention.`);
if (live(judge) && judge)
  for (const [slot, v] of Object.entries(judge.perSlot))
    if (v.wins + v.losses > 0 && v.wins <= v.losses) negatives.push(`Automated judge: in the **${slot}** slot House Mix did not beat L0 (${v.wins}–${v.losses}, ties ${v.ties}).`);
if (live(ab) && ab)
  for (const [slot, v] of Object.entries(ab.perSlot))
    if (v.winRate.hi < 0.5 || v.wins <= v.losses) negatives.push(`In the **${slot}** slot House Mix did not beat L0 (${v.wins}–${v.losses}, ties ${v.ties}).`);
if (live(bt) && bt) {
  if (bt.test.houseMix.hitAt10 <= bt.test.l0.hitAt10) negatives.push(`On hit@10, House Mix (${pct(bt.test.houseMix.hitAt10)}) did not beat the LLM-only ranking (${pct(bt.test.l0.hitAt10)}).`);
  const unresolved = bt.rows.filter((x) => x.truthResolved === 0).length;
  if (unresolved) negatives.push(`For ${unresolved} of ${bt.rows.length} test shows Qloo could not unambiguously resolve the real support act, so the Qloo methods could not rank it at all.`);
}
out.push(
  negatives.length
    ? negatives.map((n) => `- ${n}`).join("\n")
    : "Pending live results. The expected weak spot is comedy openers, where Qloo coverage of working comedians is thinner; the report will state whatever the data shows.",
);
out.push(
  "",
  "## Methods",
  "",
  "- **A/B** (`eval/ab_blind/`): 9 real shows from 2025 and January 2026 (4 concerts, 2 comedy, 3 football/baseball), each listing checked on 30 Oct 2026 (three dates corrected, one unverifiable show dropped; see `eval/data/ab_shows.json`). House Mix vs L0 (same model and brief, no Qloo), identical format, labels stripped, sides randomised with a fixed seed. Raters use `/rate`. Wilson 95% CI, Fleiss' κ. The 2 dev shows were used to tune prompts; results are on the 7 test shows.",
  "- **Automated judge** (`eval/ab_blind/judge.ts`): the same blind pairs judged by a different Claude model than the planner, once in each order; a system wins a pair only if preferred in both orders, otherwise it is a tie. It is a secondary signal until human ratings are in.",
  "- **Backtest** (`eval/backtest/`): setlist.fm 2025 shows with listed support acts; pool = true support + distractors from other shows' support acts in the same genre bucket; `qloo_rank` tournament (5×10 → top 2 → final 10) because a rank call takes ≤10 options and scores across calls are not comparable. P0 = the same tournament with only the city as a signal. L0 = Claude ranks the pool from knowledge. Settings chosen on 5 dev shows; reported on the rest.",
  "- **Evidence** (`eval/evidence/`): a citation is valid when the cited call exists in the ledger and its results contain the entity. Hallucinated entities = L0 picks Qloo cannot resolve.",
  "",
);
fs.writeFileSync(path.join(EVAL_ROOT, "REPORT.md"), `${out.join("\n")}\n`);

// The landing page's "tested on live Qloo" strip reads this summary at build time. Live results only.
const verify = r<{ qlooMode?: string; tools: number; passed: number; harness: string; at: string }>("verify");
const summary = {
  generatedAt: new Date().toISOString(),
  verify: verify ? { tools: verify.tools, passed: verify.passed, harness: verify.harness, at: verify.at } : null,
  judge:
    live(judge) && judge
      ? { model: judge.model, pairs: judge.pairs, wins: judge.overall.wins, losses: judge.overall.losses, ties: judge.overall.ties, fitHouseMix: judge.fit.houseMix, fitL0: judge.fit.l0 }
      : null,
  evidence:
    live(ev) && ev
      ? {
          items: ev.houseMix.items,
          valid: ev.houseMix.valid,
          rate: ev.houseMix.rate,
          criticDrops: ev.houseMix.criticDrops,
          l0Items: ev.l0.items,
          l0Unresolved: ev.l0.unresolvedByQloo,
          l0Ambiguous: ev.l0.ambiguousInQloo ?? null,
        }
      : null,
  judgeV1: live(judgeV1) && judgeV1 ? { wins: judgeV1.overall.wins, losses: judgeV1.overall.losses, ties: judgeV1.overall.ties } : null,
  value:
    live(value) && value
      ? {
          brandsRepeated: value.specificity.houseMixBrands.repeated,
          brands: value.specificity.houseMixBrands.picks,
          l0BrandsRepeated: value.specificity.l0Brands.repeated,
          l0Brands: value.specificity.l0Brands.picks,
          tooBig: value.realism.houseMixV2.tooBig,
          acts: value.realism.houseMixV2.picks,
          l0TooBig: value.realism.l0.tooBig,
          l0Acts: value.realism.l0.picks,
          ...(value.explainability ? { explained: value.explainability.explained, picks: value.explainability.picks } : {}),
          ...(value.repeatability ? { repeatSame: value.repeatability.sameOrder, repeatCalls: value.repeatability.calls } : {}),
          ...(value.location ? { awayOverlap: value.location.meanAwayOverlap } : {}),
        }
      : null,
  plans:
    live(plans) && plans?.plans.length
      ? {
          n: plans.plans.length,
          medianSeconds: Math.round(median(plans.plans.map((x) => x.durationMs)) / 1000),
          medianCalls: median(plans.plans.map((x) => x.stats.qlooCalls)),
          medianCostUsd: median(plans.plans.map((x) => x.stats.costUsd)),
        }
      : null,
  humanAb: live(ab) && ab && ab.ratings ? { raters: ab.raters, wins: ab.overall.wins, losses: ab.overall.losses } : null,
};
fs.writeFileSync(path.join(EVAL_ROOT, "../apps/web/lib/eval-summary.json"), `${JSON.stringify(summary, null, 2)}\n`);
console.log("wrote eval/REPORT.md");
